class TechnicianModel {
  const TechnicianModel({
    required this.name,
    required this.role,
    required this.email,
    required this.phone,
    required this.zone,
    required this.employeeId,
    required this.shift,
    required this.address,
    required this.city,
    required this.state,
    required this.pincode,
    required this.country,
  });

  final String name;
  final String role;
  final String email;
  final String phone;
  final String zone;
  final String employeeId;
  final String shift;
  final String address;
  final String city;
  final String state;
  final String pincode;
  final String country;
}


